const localeTags: Record<Language, string> = {
  en: "en-US",
  ur: "ur-PK",
  es: "es-ES",
  fr: "fr-FR",
  de: "de-DE",
  ar: "ar",
};

export function useI18n() {
  const { user } = useAuth();
  const db = useDb();
  const settings = db.user_settings.find((row) => row.user_id === user?.id);
  const language = settings?.language ?? "en";
  const rtl = language === "ur" || language === "ar";
  const t = useCallback(
    (key: MessageKey) => messages[language][key] ?? messages.en[key],
    [language],
  );

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = rtl ? "rtl" : "ltr";
    document.documentElement.classList.toggle("high-contrast", settings?.high_contrast ?? false);
    document.documentElement.classList.toggle("reduced-motion", settings?.reduced_motion ?? false);
  }, [language, rtl, settings?.high_contrast, settings?.reduced_motion]);

  return {
    language,
    locale: localeTags[language],
    rtl,
    t,
  };
}
